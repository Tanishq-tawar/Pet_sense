from django.db import models


class HealthAnalysis(models.Model):
    STATUS_CHOICES = [
        ('pending', 'Pending'),
        ('processing', 'Processing'),
        ('completed', 'Completed'),
        ('failed', 'Failed'),
    ]
    MODE_CHOICES = [
        ('standard', 'Standard Analysis'),
        ('model_v1', 'Model v1'),
        ('demo', 'Demo Mode'),
    ]

    upload = models.OneToOneField(
        'media_uploads.MediaUpload',
        on_delete=models.CASCADE,
        related_name='analysis',
    )
    status = models.CharField(max_length=20, choices=STATUS_CHOICES, default='pending')
    mode = models.CharField(max_length=20, choices=MODE_CHOICES, default='standard')
    overall_assessment = models.TextField(blank=True)
    started_at = models.DateTimeField(null=True, blank=True)
    completed_at = models.DateTimeField(null=True, blank=True)
    error_message = models.TextField(blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['-created_at']
        verbose_name = 'Health Analysis'
        verbose_name_plural = 'Health Analyses'

    def __str__(self):
        return f'Analysis #{self.pk} – {self.upload.pet.name}'


class AnalysisObservation(models.Model):
    CATEGORY_CHOICES = [
        ('coat_skin', 'Coat & Skin'),
        ('eyes', 'Eyes'),
        ('ears', 'Ears'),
        ('posture', 'Posture & Movement'),
        ('body_condition', 'Body Condition'),
        ('other', 'Other'),
    ]
    SEVERITY_CHOICES = [
        ('normal', 'Normal'),
        ('watch', 'Watch'),
        ('concern', 'Concern'),
        ('urgent', 'Urgent'),
    ]

    analysis = models.ForeignKey(
        HealthAnalysis, on_delete=models.CASCADE, related_name='observations'
    )
    category = models.CharField(max_length=30, choices=CATEGORY_CHOICES)
    title = models.CharField(max_length=200)
    description = models.TextField()
    severity = models.CharField(max_length=20, choices=SEVERITY_CHOICES, default='normal')
    confidence = models.FloatField(
        null=True, blank=True,
        help_text='Confidence score 0-1; only set when produced by a calibrated model',
    )
    recommendation = models.TextField(blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['category']

    def __str__(self):
        return f'{self.analysis} – {self.category}: {self.title}'


class HealthReport(models.Model):
    analysis = models.OneToOneField(
        HealthAnalysis, on_delete=models.CASCADE, related_name='report'
    )
    summary = models.TextField()
    recommendations = models.TextField()
    disclaimer = models.TextField(
        default=(
            'IMPORTANT: This report was generated by Pet Sense and contains '
            'preliminary health observations. It is NOT a substitute for veterinary diagnosis. '
            'Always consult a qualified veterinarian before making health decisions for your pet.'
        )
    )
    pdf_file = models.FileField(upload_to='reports/pdf/', null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    def __str__(self):
        return f'Report for {self.analysis}'
